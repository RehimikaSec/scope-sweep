"""
Builds the synthetic app catalog ScopeSweep plays against.

Every app is a *generic archetype instance* -- "Quiz Tool #7" -- not a real
product, generated by combining a category's expected/plausible scopes with
a controlled amount of extra, sometimes-outlier scopes. This keeps the
dataset realistic (grounded in Google's real scope taxonomy and real
category-appropriate access patterns) without making any claim about a real
company's actual app.

Run directly to regenerate data/apps_dataset.json:
    python3 -m data.generate_dataset
"""

from __future__ import annotations
import json
import random
from pathlib import Path

from data.categories_reference import CATEGORIES
from data.scopes_reference import SCOPES
from ml.scoring import score_app

random.seed(42)  # reproducible dataset

ADJECTIVES = ["Bright", "Quick", "Nimble", "Sunny", "Curious", "Steady", "Clever",
              "Kind", "Vivid", "Brisk", "Gentle", "Sharp", "Lively", "Calm", "Bold"]
NOUNS = ["Fox", "Otter", "Comet", "Maple", "River", "Falcon", "Pine", "Harbor",
         "Meadow", "Ember", "Willow", "Sparrow", "Cedar", "Beacon", "Orbit"]

OTHER_SCOPES = list(SCOPES.keys())

# Publisher-trust archetypes, drawn *independently* of how over-permissioned
# an app's scope list is. This independence is deliberate: it's what
# produces genuine counter-examples in the dataset -- a brand-new,
# unverified publisher that only ever asks for three harmless scopes, and a
# long-established, verified, widely-installed publisher that still
# over-requests. Without those counter-examples, "new + unverified" would
# just be a second proxy for "risky," and the model (and a skeptical judge)
# would be right to call that redundant rather than a real interaction.
#   name                       weight  age_days range   install_count range
TRUST_ARCHETYPES = [
    ("new_unverified",         0.25,  (5, 120),     (5, 300)),
    ("established_unverified", 0.15,  (400, 2500),  (50, 3000)),
    ("new_verified",          0.15,  (10, 180),    (20, 1500)),
    ("established_verified",   0.45,  (300, 3000),  (500, 60000)),
]


def _generate_publisher_metadata() -> dict:
    names = [t[0] for t in TRUST_ARCHETYPES]
    weights = [t[1] for t in TRUST_ARCHETYPES]
    chosen = random.choices(names, weights=weights, k=1)[0]
    _, _, age_range, install_range = next(t for t in TRUST_ARCHETYPES if t[0] == chosen)
    return {
        "publisher_verified": "verified" in chosen,
        "account_age_days": random.randint(*age_range),
        "install_count": random.randint(*install_range),
    }


def _generate_app(app_id: int, category: str) -> dict:
    cat = CATEGORIES[category]
    expected = list(cat["expected"])
    plausible_extra = list(cat["plausible_extra"])
    outliers = list(cat["outlier_examples"])

    # Every app gets its category's core expected scopes.
    scopes = set(expected)

    # ~55% chance to add each plausible-extra scope (still reasonable).
    for s in plausible_extra:
        if random.random() < 0.55:
            scopes.add(s)

    # Decide how "over-permissioned" this instance is:
    #   55% well-behaved (no outliers)
    #   30% mildly over-permissioned (1 outlier scope)
    #   15% clearly over-permissioned (2-3 outlier scopes, possibly a
    #       dangerous combination)
    roll = random.random()
    if roll < 0.55:
        n_outliers = 0
    elif roll < 0.85:
        n_outliers = 1
    else:
        n_outliers = random.choice([2, 3])

    if n_outliers and outliers:
        chosen = random.sample(outliers, k=min(n_outliers, len(outliers)))
        scopes.update(chosen)

    # Small chance of one extra random scope from anywhere, to keep the
    # dataset from being perfectly predictable from category alone.
    if random.random() < 0.12:
        scopes.add(random.choice(OTHER_SCOPES))

    name = f"{random.choice(ADJECTIVES)}{random.choice(NOUNS)}"
    publisher = _generate_publisher_metadata()
    result = score_app(
        category, sorted(scopes),
        publisher_verified=publisher["publisher_verified"],
        account_age_days=publisher["account_age_days"],
        install_count=publisher["install_count"],
    )

    return {
        "id": f"app-{app_id:03d}",
        "name": name,
        "category": category,
        "description": f"A {category.lower()} used in K-12 classrooms.",
        "scopes": sorted(scopes),
        "publisher_verified": publisher["publisher_verified"],
        "account_age_days": publisher["account_age_days"],
        "install_count": publisher["install_count"],
        "ground_truth_score": result.score,
        "ground_truth_tier": result.tier,
        "reasons": result.reasons,
        "tripped_combos": result.tripped_combos,
    }


def build_dataset(n_per_category: int = 10) -> list[dict]:
    apps = []
    app_id = 1
    for category in CATEGORIES:
        for _ in range(n_per_category):
            apps.append(_generate_app(app_id, category))
            app_id += 1
    random.shuffle(apps)
    return apps


def main():
    apps = build_dataset(n_per_category=10)
    out_path = Path(__file__).parent / "apps_dataset.json"
    out_path.write_text(json.dumps(apps, indent=2))
    tiers = {}
    for a in apps:
        tiers[a["ground_truth_tier"]] = tiers.get(a["ground_truth_tier"], 0) + 1
    print(f"Wrote {len(apps)} apps to {out_path}")
    print(f"Tier distribution: {tiers}")


if __name__ == "__main__":
    main()
